export const RECIPES: Recipe[] = [...CORE_RECIPES, ...MORE_RECIPES];

export const RECIPE_BY_ID: Record<string, Recipe> = Object.fromEntries(
  RECIPES.map((recipe) => [recipe.id, recipe]),
);

export function getRecipe(id: string): Recipe {
  const recipe = RECIPE_BY_ID[id];
  if (!recipe) {
    throw new Error(`找不到食谱：${id}`);
  }
  return recipe;
}

export function recipesBySlot(slot: Recipe["slot"]): Recipe[] {
  return RECIPES.filter((recipe) => recipe.slot === slot);
}
